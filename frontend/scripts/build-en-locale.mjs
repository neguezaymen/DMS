function mapVal(v) {
  if (typeof v === 'string') {
    if (Object.prototype.hasOwnProperty.call(STR, v)) return STR[v]
    return v
  }
  if (Array.isArray(v)) return v.map(mapVal)
  if (v && typeof v === 'object') {
    const o = {}
    for (const [k, x] of Object.entries(v)) o[k] = mapVal(x)
    return o
  }
  return v
}

